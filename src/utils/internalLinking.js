/**
 * Scan content and return smart suggestions
 */
export const scanForInternalLinks = (htmlOrText = "", currentSlug = "") => {
  if (!htmlOrText) return [];
  const lower = htmlOrText.toLowerCase();
  const suggestions = [];

  for (const entry of INTERNAL_LINK_DIRECTORY) {
    if (entry.slug && currentSlug && entry.slug === currentSlug) {
      continue; // Skip self-linking
    }

    for (const kw of entry.keywords) {
      if (lower.includes(kw)) {
        // Check if not already linked in content
        if (!lower.includes(`href="${entry.targetUrl}"`) && !lower.includes(`href='${entry.targetUrl}'`)) {
          suggestions.push({
            keyword: kw,
            targetUrl: entry.targetUrl,
            targetTitle: entry.targetTitle,
            type: entry.type,
          });
          break;
        }
      }
    }
  }

  return suggestions;
};

/**
 * Automatically inject natural internal links into HTML without breaking existing tags
 */
export const autoInjectInternalLinks = (htmlContent = "", currentSlug = "", maxLinks = 3) => {
  if (!htmlContent) return htmlContent;

  let modifiedHtml = htmlContent;
  let linksAdded = 0;

  for (const entry of INTERNAL_LINK_DIRECTORY) {
    if (linksAdded >= maxLinks) break;
    if (entry.slug && currentSlug && entry.slug === currentSlug) continue;

    // Check if already linked
    if (modifiedHtml.includes(entry.targetUrl)) continue;

    for (const kw of entry.keywords) {
      if (linksAdded >= maxLinks) break;

      // Regex matching keyword outside of existing HTML tags/attributes
      const regex = new RegExp(`(?<!<[^>]*)\\b(${kw.replace(/[.*+?^${}()|[\\]\\]/g, "\\$&")})\\b(?![^<]*>|[^<>]*<\\/a>)`, "i");

      if (regex.test(modifiedHtml)) {
        modifiedHtml = modifiedHtml.replace(
          regex,
          `<a href="${entry.targetUrl}" class="text-indigo-600 font-semibold hover:underline" title="${entry.targetTitle}">$1</a>`
        );
        linksAdded++;
        break;
      }
    }
  }

  return modifiedHtml;
};
